-- 040_profile_database.sql
-- Admin Panel → Database tab: browse and edit soil profile data (analytical
-- and descriptive), attach photographs to a profile, print a profile report.
-- Idempotent.

-- 1. Descriptive results follow their object. The four result_desc_* tables
--    referenced plot / profile / element without ON DELETE CASCADE, so once a
--    profile carried a field description, deleting it (project delete,
--    dataset prune, "delete profile data") failed on the foreign key.
ALTER TABLE soil_data.result_desc_plot
    DROP CONSTRAINT IF EXISTS fk_plot,
    ADD  CONSTRAINT fk_plot FOREIGN KEY (plot_id)
         REFERENCES soil_data.plot(plot_id) ON UPDATE CASCADE ON DELETE CASCADE;

ALTER TABLE soil_data.result_desc_surface
    DROP CONSTRAINT IF EXISTS fk_surface,
    ADD  CONSTRAINT fk_surface FOREIGN KEY (surface_id)
         REFERENCES soil_data.plot(plot_id) ON UPDATE CASCADE ON DELETE CASCADE;

ALTER TABLE soil_data.result_desc_profile
    DROP CONSTRAINT IF EXISTS fk_profile,
    ADD  CONSTRAINT fk_profile FOREIGN KEY (profile_id)
         REFERENCES soil_data.profile(profile_id) ON UPDATE CASCADE ON DELETE CASCADE;

ALTER TABLE soil_data.result_desc_element
    DROP CONSTRAINT IF EXISTS fk_element,
    ADD  CONSTRAINT fk_element FOREIGN KEY (element_id)
         REFERENCES soil_data.element(element_id) ON UPDATE CASCADE ON DELETE CASCADE;

-- 2. Profile photographs. Stored in the database so that they travel with
--    every backup and are removed with their profile; always re-encoded by
--    the API (JPEG, capped size, no EXIF) and served only to signed-in users.
CREATE TABLE IF NOT EXISTS api.profile_photo (
    photo_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plot_id       integer NOT NULL
                  REFERENCES soil_data.plot(plot_id) ON UPDATE CASCADE ON DELETE CASCADE,
    caption       text,
    display_order integer NOT NULL DEFAULT 0,
    width         integer NOT NULL,
    height        integer NOT NULL,
    image         bytea   NOT NULL,
    thumbnail     bytea   NOT NULL,
    uploaded_by   text,
    uploaded_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_profile_photo_plot_id ON api.profile_photo (plot_id);
COMMENT ON TABLE api.profile_photo IS
    'Photographs attached to a soil profile (plot). JPEG re-encoded by the API.';

-- 3. Permission to edit profile data in the Database tab. Administrators can
--    always edit; other accounts only when an administrator grants this.
ALTER TABLE api."user"
    ADD COLUMN IF NOT EXISTS can_edit_data boolean NOT NULL DEFAULT false;
COMMENT ON COLUMN api."user".can_edit_data IS
    'May edit soil profile data in the Database tab (administrators always may).';
